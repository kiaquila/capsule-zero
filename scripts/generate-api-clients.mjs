#!/usr/bin/env node

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import YAML from "yaml";

const root = resolve(process.cwd());
const checkOnly = process.argv.includes("--check");
const openApi = YAML.parse(
  readFileSync(resolve(root, "docs_capsule_zero/adr/openapi.yaml"), "utf8"),
);
const httpMethods = ["get", "post", "patch", "delete", "put"];
const emptyObjectType = "Record<string, never>";

function localRefName(ref, expectedSection) {
  const prefix = `#/components/${expectedSection}/`;

  if (!ref?.startsWith(prefix)) {
    throw new Error(`Unsupported local reference: ${ref}`);
  }

  return ref.slice(prefix.length);
}

function resolveLocalRef(ref) {
  if (!ref?.startsWith("#/")) {
    throw new Error(`Unsupported non-local reference: ${ref}`);
  }

  return ref
    .slice(2)
    .split("/")
    .reduce((current, segment) => current?.[segment], openApi);
}

function resolveObject(object) {
  return object?.$ref ? resolveLocalRef(object.$ref) : object;
}

function toPascalCase(value) {
  const normalized = value
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim();

  return normalized
    .split(/\s+/)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join("");
}

function toPropertyKey(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value)
    ? value
    : JSON.stringify(value);
}

function indentMultiline(value, spaces) {
  const prefix = " ".repeat(spaces);
  return value.replace(/\n/g, `\n${prefix}`);
}

function unique(values) {
  return [...new Set(values)];
}

function jsonSchemaFromContent(content = {}) {
  if (content["application/json"]?.schema) {
    return content["application/json"].schema;
  }

  return Object.values(content).find((mediaType) => mediaType?.schema)?.schema;
}

function collectSuccessResponseSchemas(responses = {}) {
  const schemas = [];
  const statusCodes = [];

  for (const [statusCode, responseObject] of Object.entries(responses)) {
    if (!/^2\d\d$|^3\d\d$/.test(statusCode)) {
      continue;
    }

    statusCodes.push(statusCode);

    const response = resolveObject(responseObject);
    const schema = jsonSchemaFromContent(response?.content);

    if (schema) {
      schemas.push(schema);
    }
  }

  return { schemas, statusCodes };
}

function collectParameters(pathItem, operation) {
  return [...(pathItem.parameters || []), ...(operation.parameters || [])].map(
    resolveObject,
  );
}

function operationPayload(operation, pathItem) {
  const parameters = collectParameters(pathItem, operation);
  const { schemas: responseSchemas, statusCodes } =
    collectSuccessResponseSchemas(operation.responses);

  return {
    pathParameters: parameters.filter((parameter) => parameter.in === "path"),
    queryParameters: parameters.filter((parameter) => parameter.in === "query"),
    headerParameters: parameters.filter(
      (parameter) => parameter.in === "header",
    ),
    cookieParameters: parameters.filter(
      (parameter) => parameter.in === "cookie",
    ),
    requestSchema: jsonSchemaFromContent(operation.requestBody?.content),
    requestRequired: Boolean(operation.requestBody?.required),
    responseSchemas,
    successStatusCodes: statusCodes,
  };
}

function collectOperations() {
  const operations = [];

  for (const [path, methods] of Object.entries(openApi.paths || {})) {
    for (const method of httpMethods) {
      const operation = methods[method];

      if (!operation) {
        continue;
      }

      const payload = operationPayload(operation, methods);

      operations.push({
        method: method.toUpperCase(),
        path,
        operationId: operation.operationId,
        auth: operation["x-auth"] || "user",
        clientAvailability: operation["x-client-availability"] || "web-mobile",
        payload,
      });
    }
  }

  return operations.sort((left, right) =>
    `${left.path} ${left.method}`.localeCompare(
      `${right.path} ${right.method}`,
    ),
  );
}

function generatedHeader(target) {
  return [
    target === "ts"
      ? "// Generated file."
      : "// ignore_for_file: constant_identifier_names",
    "// Generated by scripts/generate-api-clients.mjs from docs_capsule_zero/adr/openapi.yaml.",
    "// Do not edit by hand.",
    "",
  ].join("\n");
}

function schemaToTypeScript(schema) {
  if (!schema) {
    return "unknown";
  }

  if (schema.$ref) {
    return localRefName(schema.$ref, "schemas");
  }

  if (schema.allOf) {
    return schema.allOf.map(schemaToTypeScript).join(" & ");
  }

  if (schema.oneOf || schema.anyOf) {
    return unique((schema.oneOf || schema.anyOf).map(schemaToTypeScript)).join(
      " | ",
    );
  }

  const type = schema.type;

  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }

  if (Array.isArray(type)) {
    return unique(
      type.map((entry) => schemaToTypeScript({ ...schema, type: entry })),
    ).join(" | ");
  }

  if (type === "string") {
    return "string";
  }

  if (type === "integer" || type === "number") {
    return "number";
  }

  if (type === "boolean") {
    return "boolean";
  }

  if (type === "null") {
    return "null";
  }

  if (type === "array") {
    return `Array<${schemaToTypeScript(schema.items)}>`;
  }

  if (type === "object" || schema.properties || schema.additionalProperties) {
    return objectSchemaToTypeScript(schema);
  }

  return "unknown";
}

function objectSchemaToTypeScript(schema) {
  const properties = Object.entries(schema.properties || {});
  const required = new Set(schema.required || []);
  const propertyLines = properties.map(([name, propertySchema]) => {
    const optional = required.has(name) ? "" : "?";
    const type = indentMultiline(schemaToTypeScript(propertySchema), 2);
    return `  ${toPropertyKey(name)}${optional}: ${type};`;
  });

  let objectType =
    propertyLines.length > 0
      ? `{\n${propertyLines.join("\n")}\n}`
      : emptyObjectType;

  if (schema.additionalProperties === true) {
    const mapType = "Record<string, unknown>";
    objectType =
      propertyLines.length > 0 ? `(${objectType} & ${mapType})` : mapType;
  } else if (
    schema.additionalProperties &&
    typeof schema.additionalProperties === "object"
  ) {
    const mapType = `Record<string, ${schemaToTypeScript(
      schema.additionalProperties,
    )}>`;
    objectType =
      propertyLines.length > 0 ? `(${objectType} & ${mapType})` : mapType;
  }

  return objectType;
}

function parameterGroupToTypeScript(parameters) {
  if (parameters.length === 0) {
    return emptyObjectType;
  }

  const lines = parameters.map((parameter) => {
    const required = parameter.in === "path" || parameter.required;
    const optional = required ? "" : "?";
    const type = indentMultiline(schemaToTypeScript(parameter.schema), 2);
    return `  ${toPropertyKey(parameter.name)}${optional}: ${type};`;
  });

  return `{\n${lines.join("\n")}\n}`;
}

function responseSchemasToTypeScript(schemas) {
  if (schemas.length === 0) {
    return "void";
  }

  return unique(schemas.map(schemaToTypeScript)).join(" | ");
}

function requestSchemaToTypeScript(schema) {
  return schema ? schemaToTypeScript(schema) : "never";
}

function operationTypeNames(operationId) {
  const prefix = toPascalCase(operationId);

  return {
    path: `${prefix}PathParams`,
    query: `${prefix}QueryParams`,
    header: `${prefix}HeaderParams`,
    cookie: `${prefix}CookieParams`,
    request: `${prefix}RequestBody`,
    response: `${prefix}ResponseBody`,
  };
}

function schemaRefForDescriptor(schema) {
  if (!schema) {
    return null;
  }

  if (schema.$ref?.startsWith("#/components/schemas/")) {
    return localRefName(schema.$ref, "schemas");
  }

  return schema;
}

function parameterDescriptor(parameter) {
  return {
    name: parameter.name,
    in: parameter.in,
    required: parameter.in === "path" || Boolean(parameter.required),
    schema: schemaRefForDescriptor(parameter.schema),
    style: parameter.style || null,
    explode: typeof parameter.explode === "boolean" ? parameter.explode : null,
  };
}

function operationPayloadDescriptor(operation) {
  const payload = operation.payload;

  return {
    requestRequired: payload.requestRequired,
    successStatusCodes: payload.successStatusCodes,
    requestSchema: schemaRefForDescriptor(payload.requestSchema),
    responseSchemas: payload.responseSchemas.map(schemaRefForDescriptor),
    pathParameters: payload.pathParameters.map(parameterDescriptor),
    queryParameters: payload.queryParameters.map(parameterDescriptor),
    headerParameters: payload.headerParameters.map(parameterDescriptor),
    cookieParameters: payload.cookieParameters.map(parameterDescriptor),
  };
}

function operationMetadata(operation) {
  return {
    method: operation.method,
    path: operation.path,
    operationId: operation.operationId,
    auth: operation.auth,
    clientAvailability: operation.clientAvailability,
  };
}

function generateTypeScript(operations, errorCodes) {
  const schemas = openApi.components?.schemas || {};
  const schemaTypes = Object.entries(schemas)
    .map(
      ([name, schema]) =>
        `export type ${name} = ${schemaToTypeScript(schema)};\n`,
    )
    .join("\n");
  const operationAliases = operations
    .map((operation) => {
      const names = operationTypeNames(operation.operationId);
      const payload = operation.payload;

      return [
        `export type ${names.path} = ${parameterGroupToTypeScript(
          payload.pathParameters,
        )};`,
        `export type ${names.query} = ${parameterGroupToTypeScript(
          payload.queryParameters,
        )};`,
        `export type ${names.header} = ${parameterGroupToTypeScript(
          payload.headerParameters,
        )};`,
        `export type ${names.cookie} = ${parameterGroupToTypeScript(
          payload.cookieParameters,
        )};`,
        `export type ${names.request} = ${requestSchemaToTypeScript(
          payload.requestSchema,
        )};`,
        `export type ${names.response} = ${responseSchemasToTypeScript(
          payload.responseSchemas,
        )};`,
      ].join("\n");
    })
    .join("\n\n");
  const operationPayloads = operations
    .map((operation) => {
      const names = operationTypeNames(operation.operationId);

      return `  ${operation.operationId}: {
    path: ${names.path};
    query: ${names.query};
    header: ${names.header};
    cookie: ${names.cookie};
    request: ${names.request};
    response: ${names.response};
  };`;
    })
    .join("\n");
  const operationPayloadDescriptors = Object.fromEntries(
    operations.map((operation) => [
      operation.operationId,
      operationPayloadDescriptor(operation),
    ]),
  );

  return `${generatedHeader("ts")}export const API_VERSION = ${JSON.stringify(
    openApi.info.version,
  )} as const;

export const API_OPERATIONS = ${JSON.stringify(
    operations.map(operationMetadata),
    null,
    2,
  )} as const;

export type ApiOperation = (typeof API_OPERATIONS)[number];
export type ApiOperationId = ApiOperation["operationId"];
export type ApiAuth = ApiOperation["auth"];
export type ApiClientAvailability = ApiOperation["clientAvailability"];

export const API_ERROR_CODES = ${JSON.stringify(errorCodes, null, 2)} as const;

export type ApiErrorCode = (typeof API_ERROR_CODES)[number];

${schemaTypes}export interface ApiOperationPayloads {
${operationPayloads}
}

${operationAliases}

export type ApiPathParams<T extends ApiOperationId> =
  ApiOperationPayloads[T]["path"];
export type ApiQueryParams<T extends ApiOperationId> =
  ApiOperationPayloads[T]["query"];
export type ApiHeaderParams<T extends ApiOperationId> =
  ApiOperationPayloads[T]["header"];
export type ApiCookieParams<T extends ApiOperationId> =
  ApiOperationPayloads[T]["cookie"];
export type ApiRequestBody<T extends ApiOperationId> =
  ApiOperationPayloads[T]["request"];
export type ApiResponseBody<T extends ApiOperationId> =
  ApiOperationPayloads[T]["response"];

export const API_SCHEMAS = ${JSON.stringify(schemas, null, 2)} as const;

export const API_OPERATION_PAYLOADS = ${JSON.stringify(
    operationPayloadDescriptors,
    null,
    2,
  )} as const;

export interface ApiErrorResponse {
  error: {
    code: ApiErrorCode;
    message: string;
    details?: Record<string, unknown>;
  };
}
`;
}

function writeOrCheck(path, contents) {
  const fullPath = resolve(root, path);

  if (checkOnly) {
    const current = existsSync(fullPath) ? readFileSync(fullPath, "utf8") : "";
    if (current !== contents) {
      console.error(`${path} is out of date. Run npm run generate:api.`);
      process.exitCode = 1;
    }
    return;
  }

  mkdirSync(dirname(fullPath), { recursive: true });
  writeFileSync(fullPath, contents);
}

const operations = collectOperations();
const errorCodes = openApi.components?.schemas?.ErrorCode?.enum || [];
const typeScriptClient = generateTypeScript(operations, errorCodes);

writeOrCheck("app/src/lib/api/generated/openapi.ts", typeScriptClient);

if (!process.exitCode) {
  console.log(
    `${checkOnly ? "Verified" : "Generated"} API clients for ${operations.length} operations.`,
  );
}
